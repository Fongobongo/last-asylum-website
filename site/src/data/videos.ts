export function videosFor(topic: string, lang: Lang = 'en'): Video[] {
  const langKey = `${topic}_${lang}`;
  let list: Video[] = [];

  if (langKey in rawVideos) {
    list = [...rawVideos[langKey]];
  } else if (topic in rawVideos) {
    list = [...rawVideos[topic]];
  } else {
    return [];
  }

  return list.map((v) => {
    const localizedTitle = videoTitles[v.id]?.[lang];
    return {
      ...v,
      title: localizedTitle ?? v.title,
    };
  });
}

export function getSearchQuery(topic: string, lang: Lang = 'en'): string {
  return topicSearchTerms[topic]?.[lang] ?? topicSearchTerms[topic]?.en ?? `Last Asylum Plague ${topic}`;
}

export function getTopicName(topic: string, lang: Lang = 'en'): string {
  return topicNames[topic]?.[lang] ?? topicNames[topic]?.en ?? topic;
}

export function getYouTubeSearchUrl(topic: string, lang: Lang = 'en'): string {
  const query = getSearchQuery(topic, lang);
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(query)}`;
}

